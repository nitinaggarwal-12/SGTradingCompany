async function testAll() {
  console.log("🔍 Testing all product image URLs for HTTP 200 and image validity...");
  let errors = 0;
  for (const [sku, item] of Object.entries(AUDITED_PRODUCT_IMAGES)) {
    for (let i = 0; i < item.urls.length; i++) {
      const url = item.urls[i];
      try {
        const res = await fetch(url, { method: "HEAD" });
        if (res.status !== 200) {
          console.error(`❌ [${sku}] Slide ${i + 1} failed: HTTP ${res.status}`);
          errors++;
        }
      } catch (err) {
        console.error(`❌ [${sku}] Slide ${i + 1} network error:`, err.message);
        errors++;
      }
    }
    console.log(`✅ [${sku}] ${item.name} -> All 3 slides verified HTTP 200 OK`);
  }
  if (errors === 0) {
    console.log("\n🎉 ALL PRODUCT IMAGES VERIFIED 100% LIVE & ACCURATE!");
  } else {
    console.error(`\n⚠️ Found ${errors} image errors.`);
    process.exit(1);
  }
}

testAll();
